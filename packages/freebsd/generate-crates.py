#!/usr/bin/env python3
"""Writes net/rradius/Makefile.crates from the workspace's Cargo.lock: one CARGO_CRATES entry for
every package that comes from the crates.io registry, as `make cargo-crates` would. Run it after
Cargo.lock changes:

    packages/freebsd/generate-crates.py

With --check it only compares and exits 1 when the file is out of date.
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
target = Path(__file__).resolve().parent / "net/rradius/Makefile.crates"

# Cargo.lock is regular enough to read without a TOML parser: each [[package]] block has
# name, version and, except for the workspace's own crates, source lines.
packages = []
for block in (root / "Cargo.lock").read_text(encoding="utf-8").split("[[package]]")[1:]:
    fields = dict(re.findall(r'^(name|version|source) = "([^"]*)"$', block, re.M))
    packages.append(fields)
crates = []
for package in packages:
    source = package.get("source", "")
    if source.startswith("registry+"):
        crates.append(f'{package["name"]}-{package["version"]}')
    elif source:
        sys.exit(f'{package["name"]}: source {source} is not the crates.io registry; the port cannot fetch it')
crates.sort()

lines = ["# Generated by packages/freebsd/generate-crates.py from Cargo.lock; do not edit.", ""]
for i, crate in enumerate(crates):
    head = "CARGO_CRATES=\t" if i == 0 else "\t\t"
    lines.append(f"{head}{crate}" + (" \\" if i + 1 < len(crates) else ""))
text = "\n".join(lines) + "\n"

if "--check" in sys.argv:
    sys.exit(0 if target.exists() and target.read_text(encoding="utf-8") == text else 1)
target.write_text(text, encoding="utf-8")
print(f"{len(crates)} crates -> {target.relative_to(root)}")
